create or replace function public.log_admin_activity(
  p_activity_type text,
  p_title text,
  p_detail text default null,
  p_entity_type text default null,
  p_entity_id text default null,
  p_severity text default 'info',
  p_metadata jsonb default '{}'::jsonb
) returns bigint language plpgsql security definer set search_path=public as $$
declare new_id bigint;
begin
  insert into public.admin_activity(activity_type,title,detail,entity_type,entity_id,severity,metadata)
  values(p_activity_type,p_title,p_detail,p_entity_type,p_entity_id,p_severity,p_metadata)
  returning id into new_id;
  return new_id;
end;
$$;
revoke all on function public.log_admin_activity(text,text,text,text,text,text,jsonb) from public;
grant execute on function public.log_admin_activity(text,text,text,text,text,text,jsonb) to authenticated;

create or replace function public.prepare_session_delivery_expiry()
returns trigger language plpgsql as $$
begin
  if new.status in ('entregue','pronto','ready','delivered') and
     (old.status is distinct from new.status or new.delivered_at is null) then
    new.delivered_at := coalesce(new.delivered_at,now());
    new.expires_at := coalesce(new.expires_at,new.delivered_at + make_interval(days=>greatest(new.expiry_days,1)));
  end if;
  return new;
end;
$$;
drop trigger if exists ensaios_prepare_expiry on public.ensaios;
create trigger ensaios_prepare_expiry before update on public.ensaios for each row execute function public.prepare_session_delivery_expiry();


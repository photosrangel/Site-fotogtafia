create table if not exists public.admin_activity (
  id bigint generated by default as identity primary key,
  activity_type text not null,
  title text not null,
  detail text,
  entity_type text,
  entity_id text,
  severity text not null default 'info' check (severity in ('info','success','warning','danger')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists admin_activity_created_at_idx on public.admin_activity(created_at desc);

alter table public.ensaios add column if not exists selected_photo_numbers jsonb not null default '[]'::jsonb;
